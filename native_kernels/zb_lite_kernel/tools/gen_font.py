HEADER = """/*
 * Zip Browser —— zb_lite_kernel 内置 8x16 ASCII 点阵字库（自动生成，请勿手改）
 *
 * 由 native_kernels/zb_lite_kernel/tools/gen_font.py 从 5x7 源点阵生成：
 *   源行 r (0..6) -> 目标行 1+2r, 2+2r ；源列 c (0..4) -> 目标列 1+c
 * 每个字形 16 字节，每字节一行，bit7 = 该行最左像素。
 * 覆盖 ASCII 32..126（95 个字形），字符格 8x16 像素。
 */
#ifndef ZB_LITE_FONT_H
#define ZB_LITE_FONT_H

#include <stdint.h>

#define ZB_FONT_FIRST_CHAR 32
#define ZB_FONT_LAST_CHAR 126
#define ZB_FONT_GLYPH_COUNT 95
#ifndef ZB_FONT_CELL_W
#  define ZB_FONT_CELL_W 8
#endif
#ifndef ZB_FONT_CELL_H
#  define ZB_FONT_CELL_H 16
#endif

/* 每个字形 16 行；bit7 为最左像素 */
static const uint8_t ZB_FONT8X16[ZB_FONT_GLYPH_COUNT][ZB_FONT_CELL_H] = {
"""


def build_glyph(cols):
    """5x7 列点阵 -> 8x16 行点阵（每行一个字节，bit7 最左）。"""
    rows = [0] * 16
    for r in range(7):
        bits = 0
        for c in range(5):
            if cols[c] & (1 << r):
                bits |= 0x80 >> (1 + c)
        for ty in (1 + 2 * r, 2 + 2 * r):
            rows[ty] = bits
    return rows


def render(out_path):
    lines = [HEADER]
    for idx, cols in enumerate(FONT5X7):
        ch = chr(idx + 32)
        label = {32: "(space)", 92: "(backslash)"}.get(idx + 32, ch)
        rows = build_glyph(cols)
        body = ", ".join("0x%02X" % b for b in rows)
        lines.append("    {%s}, /* %s */\n" % (body, label))
    lines.append("};\n\n#endif /* ZB_LITE_FONT_H */\n")
    text = "".join(lines)
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return len(text)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    default_out = os.path.normpath(os.path.join(here, "..", "src", "zb_lite_font.h"))
    ap = argparse.ArgumentParser(description="生成 zb_lite_kernel 的 8x16 点阵字库头文件")
    ap.add_argument("-o", "--output", default=default_out, help="输出头文件路径")
    args = ap.parse_args()
    n = render(args.output)
    print("已生成 %s（%d 字节，95 个 8x16 字形）" % (args.output, n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
